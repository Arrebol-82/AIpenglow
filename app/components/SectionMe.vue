<script setup lang="ts">
import { ref, onMounted, onBeforeUnmount } from "vue";
import { gsap } from "gsap";
import headPortrait from "../assets/images/head_portrait.webp";

const sectionRef = ref<HTMLElement | null>(null);
const sectionHeadingTitleRef = ref<HTMLElement | null>(null);
const logsRef = ref<HTMLElement | null>(null);
const portraitRef = ref<HTMLElement | null>(null);
const meCrossRef = ref<SVGSVGElement | null>(null);
const portraitRevealStyle = ref<Record<string, string>>({
  "--reveal-x": "50%",
  "--reveal-y": "50%",
  "--reveal-radius": "0px",
});

let ctx: gsap.Context | null = null;
let portraitRevealFrame = 0;

const prefersReducedMotion = () =>
  import.meta.client &&
  window.matchMedia("(prefers-reduced-motion: reduce)").matches;

const getPortraitRevealMetrics = (event: PointerEvent) => {
  const target = event.currentTarget;
  if (!(target instanceof HTMLElement)) return null;

  const rect = target.getBoundingClientRect();
  const x = event.clientX - rect.left;
  const y = event.clientY - rect.top;
  const radius = Math.ceil(
    Math.max(
      Math.hypot(x, y),
      Math.hypot(rect.width - x, y),
      Math.hypot(x, rect.height - y),
      Math.hypot(rect.width - x, rect.height - y),
    ),
  );

  return { x, y, radius };
};

const handlePortraitPointerEnter = (event: PointerEvent) => {
  const metrics = getPortraitRevealMetrics(event);
  if (!metrics) return;

  if (portraitRevealFrame) {
    cancelAnimationFrame(portraitRevealFrame);
  }

  portraitRevealStyle.value = {
    "--reveal-x": `${metrics.x}px`,
    "--reveal-y": `${metrics.y}px`,
    "--reveal-radius": "0px",
  };

  portraitRevealFrame = requestAnimationFrame(() => {
    portraitRevealStyle.value = {
      "--reveal-x": `${metrics.x}px`,
      "--reveal-y": `${metrics.y}px`,
      "--reveal-radius": `${metrics.radius}px`,
    };
    portraitRevealFrame = 0;
  });
};

const handlePortraitPointerLeave = (event: PointerEvent) => {
  const metrics = getPortraitRevealMetrics(event);
  if (!metrics) return;

  if (portraitRevealFrame) {
    cancelAnimationFrame(portraitRevealFrame);
    portraitRevealFrame = 0;
  }

  portraitRevealStyle.value = {
    "--reveal-x": `${metrics.x}px`,
    "--reveal-y": `${metrics.y}px`,
    "--reveal-radius": "0px",
  };
};

onMounted(async () => {
  if (!sectionRef.value) return;

  if (prefersReducedMotion()) {
    if (meCrossRef.value) {
      gsap.set(meCrossRef.value, { autoAlpha: 0.18 });
    }
    return;
  }

  const { ScrollTrigger } = await import("gsap/ScrollTrigger");
  gsap.registerPlugin(ScrollTrigger);

  ctx = gsap.context(() => {
    const cornerAnchors = gsap.utils.toArray<HTMLElement>(
      ".corner-anchor",
      sectionRef.value,
    );
    const topLabel =
      sectionRef.value!.querySelector<HTMLElement>(".archive-top-label");
    const topDivider =
      sectionRef.value!.querySelector<HTMLElement>(".top-divider");
    const titlePhrases = sectionHeadingTitleRef.value
      ? gsap.utils.toArray<HTMLElement>(
          ".title-phrase",
          sectionHeadingTitleRef.value,
        )
      : [];
    const logItems = logsRef.value
      ? gsap.utils.toArray<HTMLElement>(".log-item", logsRef.value)
      : [];

    gsap.set(cornerAnchors, { opacity: 0 });
    gsap.set(topLabel, { opacity: 0 });
    gsap.set(topDivider, { scaleX: 0, transformOrigin: "left center" });
    gsap.set(titlePhrases, { y: 40, opacity: 0 });
    if (portraitRef.value) {
      gsap.set(portraitRef.value, { scale: 0.97, opacity: 0 });
    }
    const charSplit = (el: HTMLElement): HTMLElement[] => {
      const chars: HTMLElement[] = [];
      const walk = (node: Node) => {
        if (node.nodeType === 3) {
          const text = node.textContent ?? "";
          const frag = document.createDocumentFragment();
          for (const ch of text) {
            const span = document.createElement("span");
            span.style.display = "inline-block";
            span.textContent = ch;
            frag.appendChild(span);
            chars.push(span);
          }
          node.parentNode?.replaceChild(frag, node);
        } else if ((node as Element).tagName !== "BR") {
          Array.from(node.childNodes).forEach(walk);
        }
      };
      walk(el);
      return chars;
    };

    const logLabelTexts: string[] = [];
    const logLabelEls: HTMLElement[] = [];
    const logChars: HTMLElement[][] = [];
    logItems.forEach((item) => {
      const divider = item.querySelector(".log-divider");
      if (divider)
        gsap.set(divider, { scaleX: 0, transformOrigin: "center center" });
      const pEl = item.querySelector<HTMLElement>("p");
      if (pEl) gsap.set(pEl, { y: -6, opacity: 0 });
      const labelEl = item.querySelector<HTMLElement>(".log-label");
      if (labelEl) {
        logLabelTexts.push(labelEl.textContent ?? "");
        logLabelEls.push(labelEl);
      }
      const chars: HTMLElement[] = [];
      if (labelEl) chars.push(...charSplit(labelEl));
      gsap.set(chars, { y: -16, opacity: 0 });
      logChars.push(chars);
    });

    const traceMotionTweens: gsap.core.Tween[] = [];
    let auditLines: SVGPathElement[] = [];
    let traceLines: SVGPathElement[] = [];
    const restingLineOpacities = [
      0.18, 0.22, 0.19, 0.25, 0.2, 0.19, 0.23, 0.19, 0.26,
    ];

    const ambientLinesTl = gsap.timeline({
      paused: true,
      repeat: -1,
      defaults: { ease: "sine.inOut" },
    });

    if (meCrossRef.value) {
      auditLines = gsap.utils.toArray<SVGPathElement>(
        ".audit-line",
        meCrossRef.value,
      );
      traceLines = gsap.utils.toArray<SVGPathElement>(
        ".audit-line-trace",
        meCrossRef.value,
      );

      auditLines.forEach((line) => {
        const length = line.getTotalLength();
        gsap.set(line, {
          strokeDasharray: length,
          strokeDashoffset: length,
          opacity: 0,
        });
      });

      traceLines.forEach((line, index) => {
        const length = line.getTotalLength();
        const segment = Math.max(Math.min(length * 0.18, 120), 48);
        const cycle = length + segment;
        const phase = (cycle / Math.max(traceLines.length, 1)) * index;
        gsap.set(line, {
          strokeDasharray: `${segment} ${length}`,
          strokeDashoffset: phase,
          opacity: 0,
        });
      });

      ambientLinesTl
        .to(
          auditLines,
          {
            opacity: (i: number) =>
              Math.min((restingLineOpacities[i] ?? 0.16) + 0.08, 0.3),
            duration: 2.2,
            stagger: { each: 0.08, from: "start" },
          },
          0,
        )
        .to(
          auditLines,
          {
            opacity: (i: number) => restingLineOpacities[i] ?? 0.16,
            duration: 2.2,
            stagger: { each: 0.08, from: "end" },
          },
          2.2,
        );

      traceLines.forEach((line, index) => {
        const length = line.getTotalLength();
        const segment = Math.max(Math.min(length * 0.18, 120), 48);
        const cycle = length + segment;
        traceMotionTweens.push(
          gsap.to(line, {
            paused: true,
            strokeDashoffset: `-=${cycle}`,
            duration: 4.2 + index * 0.18,
            ease: "none",
            repeat: -1,
          }),
        );
      });
    }

    const masterTl = gsap.timeline({
      delay: 0.2,
      scrollTrigger: {
        trigger: sectionRef.value,
        start: "center 60%",
        once: true,
      },
      onComplete: () => {
        logLabelEls.forEach((el, i) => {
          el.textContent = logLabelTexts[i] ?? "";
        });
      },
    });

    masterTl
      .to(cornerAnchors, {
        opacity: 0.6,
        duration: 0.28,
        stagger: 0.07,
        ease: "power2.out",
      })
      .to(
        topLabel,
        { opacity: 0.6, duration: 0.28, ease: "power2.out" },
        "<0.06",
      )
      .to(
        topDivider,
        { scaleX: 1, duration: 0.65, ease: "power3.inOut" },
        "-=0.08",
      );

    if (auditLines.length) {
      masterTl
        .set(meCrossRef.value, { autoAlpha: 1 })
        .to(
          auditLines,
          {
            strokeDashoffset: 0,
            opacity: (i: number) =>
              Math.max((restingLineOpacities[i] ?? 0.16) + 0.1, 0.24),
            duration: 1.3,
            stagger: { each: 0.09, from: "end" },
            ease: "power2.out",
          },
          "-=0.05",
        )
        .to(
          auditLines,
          {
            opacity: (i: number) => restingLineOpacities[i] ?? 0.16,
            duration: 0.9,
            stagger: { each: 0.05, from: "start" },
            ease: "sine.out",
          },
          "-=0.3",
        )
        .to(
          traceLines,
          {
            opacity: 0.42,
            duration: 0.35,
            stagger: { each: 0.04, from: "end" },
          },
          "-=0.4",
        )
        .add(() => {
          ambientLinesTl.play(0);
          traceMotionTweens.forEach((t) => t.play(0));
        });
    }

    masterTl.to(
      titlePhrases,
      {
        y: 0,
        opacity: 1,
        duration: 1.2,
        stagger: 0.12,
        ease: "power3.out",
        onStart: () => {
          sectionRef.value?.classList.add("is-active");
        },
      },
      "-=0.5",
    );

    if (portraitRef.value) {
      masterTl.to(
        portraitRef.value,
        {
          scale: 1,
          opacity: 1,
          duration: 1.5,
          ease: "power3.out",
        },
        "<",
      );
    }

    masterTl.addLabel("logStart", "-=0.4");

    logItems.forEach((item, i) => {
      const divider = item.querySelector<HTMLElement>(".log-divider");
      const pEl = item.querySelector<HTMLElement>("p");
      const chars = logChars[i] ?? [];
      const itemStart = i === 0 ? "logStart" : ">0.15";

      if (divider) {
        masterTl.to(
          divider,
          { scaleX: 1, duration: 0.38, ease: "power3.inOut" },
          itemStart,
        );
      }
      if (pEl) {
        masterTl.to(
          pEl,
          { y: 0, opacity: 1, duration: 0.45, ease: "power2.out" },
          "<0.2",
        );
      }
      masterTl.to(
        chars,
        { y: 0, opacity: 1, duration: 0.25, stagger: 0.02, ease: "power2.out" },
        ">0.05",
      );
    });
  }, sectionRef.value);
});

onBeforeUnmount(() => {
  if (portraitRevealFrame) {
    cancelAnimationFrame(portraitRevealFrame);
  }
  ctx?.revert();
});
</script>

